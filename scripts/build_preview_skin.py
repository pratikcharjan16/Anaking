#!/usr/bin/env python3
"""Generate static/css/preview-skin.css: survey.css scoped under `.survey-skin` so the Studio's
question test view looks exactly like the respondent survey without restyling the Studio.

Re-run after editing survey.css:      python3 scripts/build_preview_skin.py
Verify the checked-in file is current: python3 scripts/build_preview_skin.py --check

The skin carries structure only - no palette. `.survey-skin` is declared next to
`.theme-instrument` in design-system.css, so the preview borrows the instrument tokens and
can never drift from the real questionnaire.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "static", "css", "survey.css")
DST = os.path.join(ROOT, "static", "css", "preview-skin.css")
SKIP = ("html", "body", "main", "header", ".topbar", ".brand", ".hud", ".meta", ".progress", ".teambar",
        ".appnav", "[hidden]", ".overlay", ".tpp-panel", ".celebrate", ".coach", ".toast", ".confetti")


def scope(selector: str) -> str | None:
    sel = selector.strip()
    if not sel or sel.startswith("@") or sel in ("from", "to") or re.fullmatch(r"\d+%", sel):
        return sel
    if sel == ":root":
        return ".survey-skin"
    if any(sel == s or sel.startswith(s + " ") or sel.startswith(s + ".") or sel.startswith(s + ":") for s in SKIP):
        return None
    sel = re.sub(r"^body\.testmode\s+", ".survey-skin.testmode ", sel)
    return ".survey-skin " + sel


def render() -> str:
    """Return the generated stylesheet as text (no side effects)."""
    css = open(SRC, encoding="utf-8").read()
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out = []

    # simple tokenizer: handles nested @media/@keyframes blocks
    def emit_block(prelude, body):
        p = prelude.strip()
        if p.startswith("@media") or p.startswith("@supports"):
            inner = build(body)
            if inner.strip():
                out.append(p + "{" + inner + "}")
        elif p.startswith("@keyframes") or p.startswith("@font-face"):
            out.append(p + "{" + body + "}")
        else:
            sels = [scope(s) for s in p.split(",")]
            sels = [s for s in sels if s]
            if sels:
                out.append(",".join(sels) + "{" + body.strip() + "}")

    def build(text):
        res, j, d, pre, start = [], 0, 0, "", 0
        while j < len(text):
            ch = text[j]
            if ch == "{":
                if d == 0:
                    pre = text[start:j]; start = j + 1
                d += 1
            elif ch == "}":
                d -= 1
                if d == 0:
                    body = text[start:j]
                    saved = out[:]
                    del out[:]
                    emit_block(pre, body)
                    res.extend(out); del out[:]; out.extend(saved)
                    start = j + 1
            j += 1
        return "\n".join(res)

    header = (
        "/* GENERATED by scripts/build_preview_skin.py from survey.css - do not edit by hand.\n"
        "   Survey styles scoped under .survey-skin for the Studio question test view.\n"
        "   Structure only: the palette comes from .survey-skin in design-system.css. */\n"
        ".survey-skin{font:15px/1.55 -apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;color:var(--ink)}\n"
        ".survey-skin .btn.primary{margin-top:12px}\n"
        ".survey-skin .err.ok{background:var(--good-soft);color:var(--good);border-color:var(--good)}\n"
    )
    return header + build(css) + "\n"


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    css = render()
    current = ""
    if os.path.exists(DST):
        current = open(DST, encoding="utf-8").read()
    if "--check" in argv:
        if current != css:
            print("preview-skin.css is stale - run scripts/build_preview_skin.py")
            return 1
        print("preview-skin.css is up to date")
        return 0
    if current == css:
        print("preview-skin.css already up to date")
        return 0
    open(DST, "w", encoding="utf-8").write(css)
    print("wrote", os.path.relpath(DST, ROOT), len(css), "bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
